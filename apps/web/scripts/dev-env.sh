#!/usr/bin/env bash
# Writes apps/web/.env.development.local from a deployed environment, for `pnpm dev` (8.3).
# Everything here is public client configuration (no secrets); the file is gitignored anyway
# because it is per developer. Needs an SSO session for the environment (reads its tofu state).
#   pnpm --filter @photo-app/web env:dev        # default env: dev
set -euo pipefail

ENV="${1:-dev}"
cd "$(dirname "$0")/.."
ENV_DIR="../../infra/envs/$ENV"

out() { AWS_PROFILE="$ENV" tofu -chdir="$ENV_DIR" output -raw "$1"; }

pool_id="$(out user_pool_id)"
client_id="$(out web_client_id)"

# The login page offers "Continue with Google" only if the app client actually allows Google (4.4).
providers="$(AWS_PROFILE="$ENV" aws cognito-idp describe-user-pool-client \
  --user-pool-id "$pool_id" --client-id "$client_id" \
  --query 'UserPoolClient.SupportedIdentityProviders' --output text)"
google=false
[[ "$providers" == *Google* ]] && google=true

cat > .env.development.local <<ENVFILE
# Generated by scripts/dev-env.sh $ENV on $(date -u +%Y-%m-%dT%H:%MZ). Public client config only.
VITE_COGNITO_USER_POOL_ID=$pool_id
VITE_COGNITO_CLIENT_ID=$client_id
VITE_COGNITO_DOMAIN=$(out cognito_domain_url)
VITE_GOOGLE_LOGIN=$google
# Read by vite.config.ts only (not exposed to the browser): /api and /users proxy targets.
API_PROXY_TARGET=$(out api_endpoint)
MEDIA_PROXY_TARGET=$(out app_url)
ENVFILE

echo "wrote apps/web/.env.development.local for $ENV (Google login: $google)"
